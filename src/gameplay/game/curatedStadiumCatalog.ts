interface CuratedStadiumSpec {
  id: string;
  slotNumber: number;
  name: string;
  shortName: string;
  city: string;
  country: string;
  shape: StadiumShape;
  hasTrack: boolean;
  surroundings: SurroundingsType;
  grounds?: StadiumGroundsType;
  standGrade: StandConfig['grade'];
  archGrade: ArchitecturalGrade;
  tierCount: 1 | 2 | 3 | 4;
  tier: StadiumTier;
  primaryColor: string;
  secondaryColor: string;
  roof: RoofConfig;
  seatStyle: SeatStyle;
  benchType: BenchType;
  benchQuality: BenchQualityTier;
  tunnelType: TunnelType;
  turfQuality: TurfQuality;
  mowingPattern: LawnMowingPattern;
  timeOfDay: TimeOfDay;
  pylonCount: 0 | 2 | 4 | 6;
  powerKw: number;
  capacityOverride?: number;
  goalFrame?: GoalFrameType;
  netTension?: NetTension;
  hasVipZone?: boolean;
  hasVipSeats?: boolean;
  hasTransmissionArea?: boolean;
  standsOverride?: Partial<Record<StandPosition, Partial<StandConfig>>>;
}

function buildCuratedStands(spec: CuratedStadiumSpec): Record<StandPosition, StandConfig> {
  const positions: StandPosition[] = [
    'east',
    'west',
    'north',
    'south',
    'corner_ne',
    'corner_nw',
    'corner_se',
    'corner_sw',
  ];

  const isElite = spec.tier === 'monumental';
  const stands = {} as Record<StandPosition, StandConfig>;

  for (const pos of positions) {
    const isCorner = pos.startsWith('corner_');
    const override = spec.standsOverride?.[pos];
    const baseTiersCount = isCorner
      ? Math.max(1, spec.tierCount - 1)
      : spec.tierCount;
    const clampedTiers = Math.min(4, Math.max(1, baseTiersCount)) as 1 | 2 | 3 | 4;
    const tierSize: TierSize = isElite
      ? isCorner
        ? 'medium'
        : 'large'
      : isCorner
      ? 'small'
      : 'medium';

    const defaultStand: StandConfig = {
      position: pos,
      type: 'tiered',
      grade: spec.standGrade,
      architecturalGrade: spec.archGrade,
      tierCount: clampedTiers,
      tiers: Array.from({ length: clampedTiers }, () => ({ size: tierSize })),
      primaryColor: spec.primaryColor,
      secondaryColor: spec.secondaryColor,
      hasRoof: spec.roof.enabled,
      roofCoverage: spec.roof.enabled ? spec.roof.coverage : 0,
      hasVipSeats: spec.hasVipSeats ?? isElite,
      hasVipZone: !isCorner && (spec.hasVipZone ?? isElite),
      hasTransmissionArea: pos === 'west' && (spec.hasTransmissionArea ?? true),
    };

    if (override) {
      stands[pos] = {
        ...defaultStand,
        ...override,
        position: pos,
      };
    } else {
      stands[pos] = defaultStand;
    }
  }

  return stands;
}

function buildCuratedStadium(spec: CuratedStadiumSpec): StadiumDefinition {
  const stands = buildCuratedStands(spec);
  const rawCapacity = calculateStadiumTotalCapacity(stands, spec.shape);
  const capacity = spec.capacityOverride || rawCapacity;
  const isElite = spec.tier === 'monumental';
  const lightingType =
    spec.pylonCount === 0
      ? 'roof_banks'
      : spec.tier === 'monumental' || spec.tier === 'craven'
      ? 'corner_pylons'
      : 'light_poles';

  return {
    id: spec.id,
    slotNumber: spec.slotNumber,
    name: spec.name,
    shortName: spec.shortName,
    city: spec.city,
    country: spec.country,
    shape: spec.shape,
    surroundings: spec.surroundings,
    grounds: spec.grounds || (isElite ? 'modern_architectural' : 'parking_lots'),
    roof: spec.roof,
    roofCutaway: spec.roof.cutawayMode || 'partial',
    hasTrack: spec.hasTrack,
    apronMaterial: spec.hasTrack
      ? 'rubber_tartan'
      : isElite
      ? 'artificial_turf'
      : 'grass',
    apronSetback: spec.hasTrack ? 'expansive' : isElite ? 'standard' : 'compact',
    stands,
    seats: {
      style: spec.seatStyle,
      pattern: isElite ? 'horizontalBands' : 'verticalStripes',
      colors: [spec.primaryColor, spec.secondaryColor, '#e2e8f0'],
    },
    lighting: {
      type: lightingType,
      pylonCount: spec.pylonCount,
      powerKw: spec.powerKw,
      timeOfDay: spec.timeOfDay,
    },
    dugouts: {
      type: spec.benchType,
      quality: spec.benchQuality,
      frameColor: spec.primaryColor,
      cushionColor: spec.secondaryColor,
      shelterTint: 'rgba(15, 23, 42, 0.88)',
      setbackDistance: isElite ? 16 : 12,
    },
    tunnel: {
      type: spec.tunnelType,
      siting: 'center_main',
      primaryColor: spec.primaryColor,
      secondaryColor: spec.secondaryColor,
      backlitLeds: spec.archGrade === 'modern',
      hasBellows: spec.tunnelType === 'inflatable_accordion',
    },
    capacity,
    fifaCategory: calculateFifaQualification(
      capacity,
      spec.standGrade,
      spec.powerKw,
      spec.turfQuality
    ),
    tier: spec.tier,
    architecturalGrade: spec.archGrade,
    pitchPreset: 'balanced',
    pitchLengthMeters: 105,
    pitchWidthMeters: 68,
    turfQuality: spec.turfQuality,
    mowingPattern: spec.mowingPattern,
    grassLength: isElite ? 'short' : 'normal',
    surfaceStatus: 'normal',
    goalFrame: spec.goalFrame || 'standard',
    netTension: spec.netTension || 'moderate',
    seatColor: 'auto',
    hasTransmissionArea: spec.hasTransmissionArea ?? true,
    hasVipZone: spec.hasVipZone ?? isElite,
    hasVipSeats: spec.hasVipSeats ?? true,
  };
}

