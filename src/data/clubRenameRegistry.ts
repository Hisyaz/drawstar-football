/**
 * Resolves the canonical non-copyrighted club name for a team ID or legacy name,
 * strictly guarding against cross-country collisions (e.g. ARG Arsenal vs ENG Arsenal).
 */
export function resolveGenericClubName(
  teamId?: string,
  currentName?: string,
  countryCode?: string
): string {
  const tid = (teamId || '').toLowerCase().trim();
  if (tid && CLUB_RENAME_MAP[tid]) {
    const rename = CLUB_RENAME_MAP[tid];
    // Only replace if current name is empty or matches a legacy real-life name
    if (!currentName || isLegacyRealClubName(currentName)) {
      return rename.name;
    }
    return currentName;
  }

  if (!currentName) return '';
  const low = currentName.trim().toLowerCase();
  const cc = (countryCode || '').toUpperCase().trim();

  // Explicit disambiguation for Arsenal (Argentina vs England)
  if (low.includes('arsenal')) {
    if (tid === 'arg_arsenal' || cc === 'ARG' || low.includes('sarand')) {
      return CLUB_RENAME_MAP.arg_arsenal.name;
    }
    if (tid === 'eng_arsenal' || cc === 'ENG' || low === 'arsenal' || low === 'arsenal fc') {
      return CLUB_RENAME_MAP.eng_arsenal.name;
    }
  }

  // Explicit disambiguation for Liverpool (Uruguay vs England)
  if (low.includes('liverpool')) {
    if (tid.includes('conmebol') || cc === 'URU' || low.includes('montevideo')) {
      return CLUB_RENAME_MAP.conmebol_liverpool_mvd.name;
    }
    return CLUB_RENAME_MAP.eng_liverpool.name;
  }

  // Explicit disambiguation for Barcelona (Ecuador vs Spain)
  if (low.includes('barcelona')) {
    if (tid.includes('conmebol') || cc === 'ECU' || low.includes('guayaquil') || low === 'barcelona sc') {
      return CLUB_RENAME_MAP.conmebol_barcelona_sc.name;
    }
    return CLUB_RENAME_MAP.esp_barcelona.name;
  }

  // Explicit disambiguation for Everton (Chile vs England)
  if (low.includes('everton')) {
    if (tid.includes('conmebol') || cc === 'CHI' || low.includes('viña') || low.includes('vina')) {
      return CLUB_RENAME_MAP.conmebol_everton_chi.name;
    }
    return CLUB_RENAME_MAP.eng_everton.name;
  }

  if (LEGACY_NAME_TO_GENERIC_MAP[low]) {
    return LEGACY_NAME_TO_GENERIC_MAP[low];
  }

  return currentName;
}

export function resolveGenericShortName(
  teamId?: string,
  currentShortName?: string,
  currentName?: string
): string {
  const tid = (teamId || '').toLowerCase().trim();
  if (tid && CLUB_RENAME_MAP[tid] && (!currentName || isLegacyRealClubName(currentName))) {
    return CLUB_RENAME_MAP[tid].shortName;
  }
  return currentShortName || '';
}

export function resolveGenericRivalList(
  rivals: string[] | undefined,
  countryCode?: string
): string[] | undefined {
  if (!Array.isArray(rivals) || rivals.length === 0) return rivals;
  return rivals.map((r) => resolveGenericClubName(undefined, r, countryCode));
}

const ALL_LEGACY_REAL_NAMES_LOWER = new Set<string>(Object.keys(LEGACY_NAME_TO_GENERIC_MAP));

/**
 * Checks whether a name is one of the legacy real-life club names in our pre-rename database
 * (excluding any already-renamed generic name).
 */
export function isLegacyRealClubName(name?: string): boolean {
  if (!name) return false;
  const low = name.trim().toLowerCase();
  if (ALL_LEGACY_REAL_NAMES_LOWER.has(low)) return true;
  // Also recognize any exact pre-rename patterns that might be cached in localStorage
  return false;
}
